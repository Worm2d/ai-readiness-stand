"""Общие модели приложения: глобальные настройки стенда (singleton)."""
from django.core.exceptions import ValidationError
from django.db import models


class SiteSettings(models.Model):
    """Глобальные редактируемые настройки лендинга, опроса и отчёта (singleton, pk=1)."""

    collect_personal_data = models.BooleanField(
        "Собирать контакты посетителя",
        default=True,
        help_text="Если включено — перед показом результата будет показана форма (имя, компания, email/телефон).",
    )
    personal_data_consent_text = models.TextField(
        "Текст согласия на обработку персональных данных",
        default="Я даю согласие на обработку моих персональных данных для подготовки и отправки отчёта.",
        help_text="Служебное поле. Используется как запасной текст согласия, если потребуется вернуть отдельное окно согласия.",
    )
    privacy_policy_file = models.FileField(
        "Файл политики конфиденциальности",
        upload_to="policy/",
        blank=True,
        null=True,
        help_text=(
            "PDF или другой документ с политикой обработки персональных данных. Ссылка на скачивание "
            "этого файла показывается в форме сбора контактов рядом с текстом согласия."
        ),
    )

    landing_title = models.CharField(
        "Заголовок стартовой страницы",
        max_length=255,
        default="А ты готов к эпохе Искусственного Интеллекта?",
    )
    landing_subtitle = models.TextField(
        "Пояснительный текст на стартовой странице",
        default=(
            "Речь идёт о защите информации в эпоху ИИ: защита локальных языковых моделей "
            "внутри организаций, защита от утечек данных через публичные ИИ-сервисы, защита "
            "от атак, сгенерированных или усиленных искусственным интеллектом, а также "
            "применение ИИ в самих средствах защиты информации."
        ),
    )
    button_text = models.CharField("Текст на кнопках старта опроса", max_length=50, default="Нет")
    result_title = models.CharField(
        "Заголовок страницы результата",
        max_length=255,
        default="Вы не готовы, но мы можем Вам помочь",
    )
    qr_hint_text = models.CharField(
        "Текст подсказки под QR-кодом отчёта",
        max_length=255,
        default="Отсканируйте, чтобы открыть отчёт на телефоне",
        help_text="Показывается под QR-кодом на странице результата опроса.",
    )
    show_score_number = models.BooleanField(
        "Показывать числовой балл и прогресс-бар",
        default=True,
        help_text=(
            "Если выключено — на странице отчёта не показывается число «N/100» и прогресс-бар. "
            "Текстовая интерпретация уровня (заголовок и описание) управляется отдельным переключателем ниже."
        ),
    )
    show_score_block = models.BooleanField(
        "Показывать текстовую интерпретацию уровня",
        default=True,
        help_text=(
            "Если выключено — не показывается текстовая интерпретация уровня готовности (например, "
            "«Критический уровень готовности», «Требует внимания», «Хороший уровень») и её описание. "
            "Числовой балл и прогресс-бар управляются отдельным переключателем выше. Заголовок «Отчёт» "
            "и подпись под ним остаются в любом случае."
        ),
    )
    show_risk_categories = models.BooleanField(
        "Показывать цветные бейджи категорий риска",
        default=True,
        help_text=(
            "Если выключено — у каждого выявленного риска в отчёте не показываются цветные бейджи "
            "категорий (например, «Утечка через публичный ИИ», «Защита локальных моделей»). "
            "Бейдж уровня критичности (низкий/средний/высокий/критический) показывается в любом случае."
        ),
    )
    show_risk_case = models.BooleanField(
        "Показывать источники (кейсы/статистику) у рисков",
        default=True,
        help_text=(
            "Если выключено — у выявленных рисков в отчёте не показывается блок с описанием публичного "
            "инцидента/статистики и ссылкой на источник. Название, описание и уровень критичности риска "
            "остаются в любом случае."
        ),
    )
    show_question_counter = models.BooleanField(
        "Показывать счётчик «Vопрос X из N» в опросе",
        default=True,
        help_text="Если выключено — во время прохождения опроса номер текущего вопроса и их общее количество не показываются.",
    )
    show_question_progress_bar = models.BooleanField(
        "Показывать прогресс-бар в опросе",
        default=True,
        help_text=(
            "Если выключено — во время прохождения опроса не показывается визуальная полоса прогресса. "
            "Управляется независимо от счётчика «Вопрос X из N» выше — можно оставить один из двух элементов."
        ),
    )

    always_recommendation_title = models.CharField(
        "Заголовок обязательной рекомендации",
        max_length=255,
        blank=True,
        default="Обратитесь к экспертам",
        help_text="Заголовок отдельного блока рекомендации, который показывается в каждом отчёте вне зависимости от ответов.",
    )
    always_recommendation_text = models.TextField(
        "Текст обязательной рекомендации",
        blank=True,
        default=(
            "Наши эксперты помогут провести аудит ИИ-контура и выстроить защиту от актуальных угроз. "
            "Свяжитесь с нами, чтобы обсудить, какие меры нужны именно вашей организации."
        ),
        help_text=(
            "Если заполнено (и заголовок, и текст) — блок с призывом обратиться в компанию показывается "
            "в каждом отчёте на корпоративном фоне, независимо от ответов на опрос. Если оставить пустым — "
            "блок не показывается. Контакты бергтся из полей «E-mail компании» и «Сайт компании» ниже."
        ),
    )
    always_recommendation_email_label = models.CharField(
        "Подпись перед email в блоке рекомендации",
        max_length=100,
        blank=True,
        default="Напишите нам:",
    )
    always_recommendation_website_label = models.CharField(
        "Подпись перед сайтом в блоке рекомендации",
        max_length=100,
        blank=True,
        default="Наш сайт:",
    )

    email_subject = models.CharField(
        "Тема письма с отчётом",
        max_length=255,
        blank=True,
        default="Ваш отчёт по готовности к ИИ-угрозам готов",
    )
    email_body_template = models.TextField(
        "Текст письма с отчётом",
        blank=True,
        default=(
            "Здравствуйте{visitor_name}!\n\n"
            "Ваш персональный отчёт по итогам опроса готов, ознакомиться с ним можно по ссылке:\n"
            "{report_url}\n\n"
            "Если вас интересует защита ИИ-контура или другие услуги по информационной безопасности, "
            "напишите нам на {company_email} — обсудим, как можем помочь именно вашей организации.\n\n"
            "Наш сайт: {company_website}"
        ),
        help_text=(
            "Текст письма, которое отправляется на email посетителя после заполнения формы контактов. "
            "Доступные плейсхолдеры (подставляются автоматически): {visitor_name} — если имя посетителя "
            "указано, подставится «, Имя» (с затепятой и пробелом перед именем), иначе — пустая строка, поэтому "
            "плейсхолдер нужно писать сразу после слова «здравствуйте» без своей запятой, например "
            "«здравствуйте{visitor_name}!» даёт «здравствуйте, Иван!» или «здравствуйте!», если имя не указано; "
            "{report_url} — ссылка на персональный отчёт; {company_name} — название компании; "
            "{company_email} — email компании; {company_website} — сайт компании. Если письмо не удалось "
            "отправить (не настроен SMTP или ошибка соединения), это не блокирует показ отчёта посетителю."
        ),
    )

    company_name = models.CharField("Название компании", max_length=255, default="ICL Системные технологии")
    company_website = models.URLField("Сайт компании", default="https://icl-st.ru/")
    company_email = models.EmailField("E-mail компании", default="office@icl-st.ru")
    primary_color = models.CharField("Основной корпоративный цвет (HEX)", max_length=7, default="#E30613")
    logo = models.ImageField("Логотип", upload_to="branding/", blank=True, null=True)
    footer_text = models.CharField(
        "Текст в подвале страниц",
        max_length=255,
        default="ICL Системные технологии — комплексная защита информации в эпоху ИИ",
    )

    class Meta:
        verbose_name = "Настройки сайта"
        verbose_name_plural = "Настройки сайта"

    def __str__(self):
        return "Глобальные настройки сайта"

    def save(self, *args, **kwargs):
        self.pk = 1
        super().save(*args, **kwargs)

    def delete(self, *args, **kwargs):
        pass

    def clean(self):
        if SiteSettings.objects.exclude(pk=self.pk).exists():
            raise ValidationError("Может существовать только одна запись настроек сайта.")

    @classmethod
    def load(cls):
        obj, _ = cls.objects.get_or_create(pk=1)
        return obj
