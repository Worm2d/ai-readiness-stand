def seed_data(apps, schema_editor):
    RiskCategory = apps.get_model("risks", "RiskCategory")
    ScoreInterpretation = apps.get_model("risks", "ScoreInterpretation")
    Risk = apps.get_model("risks", "Risk")
    Recommendation = apps.get_model("risks", "Recommendation")

    category_objs = {}
    for cat in CATEGORIES:
        obj, _ = RiskCategory.objects.get_or_create(
            name=cat["name"],
            defaults={"slug": slugify(cat["name"], allow_unicode=True), "color": cat["color"], "description": cat["description"]},
        )
        category_objs[cat["name"]] = obj

    for interp in INTERPRETATIONS:
        ScoreInterpretation.objects.get_or_create(
            min_score=interp["min_score"], max_score=interp["max_score"],
            defaults={"title": interp["title"], "description": interp["description"], "color": interp["color"]},
        )

    for order, (title, severity, description, cat_names, case_title, case_desc, case_url) in enumerate(RISKS):
        risk, _ = Risk.objects.get_or_create(
            title=title,
            defaults={
                "description": description, "severity": severity, "order": order,
                "public_case_title": case_title, "public_case_description": case_desc,
                "public_case_source_url": case_url, "public_case_region": "Россия" if case_desc else "",
            },
        )
        risk.categories.set([category_objs[name] for name in cat_names])

    for order, (title, description, cat_name) in enumerate(RECOMMENDATIONS):
        Recommendation.objects.get_or_create(
            title=title,
            defaults={
                "description": description, "order": order,
                "related_category": category_objs.get(cat_name) if cat_name else None,
            },
        )


def unseed_data(apps, schema_editor):
    Risk = apps.get_model("risks", "Risk")
    Recommendation = apps.get_model("risks", "Recommendation")
    ScoreInterpretation = apps.get_model("risks", "ScoreInterpretation")
    RiskCategory = apps.get_model("risks", "RiskCategory")
    Risk.objects.all().delete()
    Recommendation.objects.all().delete()
    ScoreInterpretation.objects.all().delete()
    RiskCategory.objects.all().delete()


